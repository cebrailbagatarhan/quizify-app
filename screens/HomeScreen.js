import React, { useState, useRef, useCallback } from 'react';
import {
  View,
  Text,
  StyleSheet,
  TouchableOpacity,
  ScrollView,
  TextInput,
  Animated,
  Dimensions,
  SafeAreaView as RNSafeAreaView,
  Modal,
  ActivityIndicator,
  Alert,
} from 'react-native';
import { LinearGradient } from 'expo-linear-gradient';
import { categories } from '../data/newQuizData';
import { generativeAIService } from '../services/generativeAIService';
import { useFocusEffect } from '@react-navigation/native';
import { StatsManager } from '../utils/statsManager';
import { displayUserName, countTodaysQuizzes } from '../utils/homeStats';
import { filterCategories } from '../utils/categorySearch';

const { width } = Dimensions.get('window');

export default function HomeScreen({ navigation }) {
  const [userName, setUserName] = useState('Kullanıcı');
  const [dailyQuizzes, setDailyQuizzes] = useState(0);
  const [categoryQuery, setCategoryQuery] = useState('');
  const [loading, setLoading] = useState(false);
  const [loadingText, setLoadingText] = useState('');
  // State updates are async: a ref blocks rapid double taps immediately.
  const quizRequestInFlight = useRef(false);
  const visibleCategories = filterCategories(categories, categoryQuery);

  // Refresh on every visit, including after changing the name or finishing a quiz.
  useFocusEffect(useCallback(() => {
    let active = true;
    const loadDashboard = async () => {
      try {
        const [profile, history] = await Promise.all([
          StatsManager.getProfile(),
          StatsManager.getQuizHistory(),
        ]);
        if (active) {
          setUserName(displayUserName(profile));
          setDailyQuizzes(countTodaysQuizzes(history));
        }
      } catch (error) {
        console.error('Error loading home dashboard:', error);
      }
    };
    loadDashboard();
    return () => { active = false; };
  }, []));

  const animatedValues = useRef(
    categories.map(() => new Animated.Value(0))
  ).current;

  React.useEffect(() => {
    const animations = animatedValues.map((value, index) =>
      Animated.timing(value, {
        toValue: 1,
        duration: 600,
        delay: index * 100,
        useNativeDriver: true,
      })
    );
    Animated.stagger(100, animations).start();
  }, []);

  const handleCategoryPress = async (category) => {
    if (quizRequestInFlight.current) return;
    quizRequestInFlight.current = true;
    setLoadingText(`"${category.name}" için sorular hazırlanıyor...`);
    setLoading(true);
    try {
      const questions = await generativeAIService.generateQuiz(category.name);
      if (questions && questions.length > 0) {
        navigation.navigate('Quiz', { category, questions });
      } else {
        Alert.alert('Hata', 'Sorular oluşturulamadı. Lütfen tekrar deneyin.');
      }
    } catch (error) {
      // Only show messages explicitly generated by our client. Network errors
      // may contain server URLs or implementation details.
      const safeMessages = [
        'Quiz sunucusu yapılandırılmamış (EXPO_PUBLIC_QUIZ_API_URL).',
        'Quiz sunucusu HTTPS kullanmalıdır.',
        'Geçersiz quiz konusu.',
        'Çok fazla istek gönderildi; lütfen daha sonra tekrar deneyin.',
        'Quiz servisi şu anda kullanılamıyor.',
        'Sunucu geçerli quiz soruları döndürmedi.',
        'Sunucudan gelen quiz yanıtı geçersiz.',
      ];
      const message = safeMessages.includes(error?.message)
        ? error.message
        : 'Quiz sunucusuna ulaşılamadı. İnternet bağlantınızı kontrol edip tekrar deneyin.';
      Alert.alert('Bir Hata Oluştu', message);
    } finally {
      quizRequestInFlight.current = false;
      setLoading(false);
    }
  };

  const CategoryCard = ({ category, index }) => {
    const animatedValue = animatedValues[index];

    return (
      <Animated.View
        style={[
          styles.cardContainer,
          {
            opacity: animatedValue,
            transform: [
              {
                translateY: animatedValue.interpolate({
                  inputRange: [0, 1],
                  outputRange: [50, 0],
                }),
              },
            ],
          },
        ]}
      >
        <TouchableOpacity
          style={styles.categoryCard}
          onPress={() => handleCategoryPress(category)}
          activeOpacity={0.8}
        >
          <LinearGradient
            colors={[category.color, `${category.color}80`]}
            style={styles.cardGradient}
          >
            <Text style={styles.categoryIcon}>{category.icon}</Text>
            <Text style={styles.categoryName}>{category.name}</Text>
            <Text style={styles.categoryDescription}>{category.description}</Text>
          </LinearGradient>
        </TouchableOpacity>
      </Animated.View>
    );
  };

  return (
    <RNSafeAreaView style={styles.container}>
      <Modal
        transparent={true}
        animationType="fade"
        visible={loading}
        onRequestClose={() => {}}
      >
        <View style={styles.modalBackground}>
          <View style={styles.activityIndicatorWrapper}>
            <ActivityIndicator size="large" color="#ffffff" />
            <Text style={styles.loadingText}>{loadingText}</Text>
          </View>
        </View>
      </Modal>

      <LinearGradient
        colors={['#f8f9fa', '#e9ecef']}
        style={styles.background}
      >
        {/* Header */}
        <View style={styles.header}>
          <View>
            <Text style={styles.greeting}>Merhaba, {userName}! 👋</Text>
            <Text style={styles.dailyStats}>
              Bugün {dailyQuizzes} quiz çözdünüz
            </Text>
          </View>
          <TouchableOpacity
            style={styles.profileButton}
            onPress={() => navigation.navigate('Profile')}
          >
            <Text style={styles.profileIcon}>👤</Text>
          </TouchableOpacity>
        </View>

        {/* Main Content */}
        <View style={styles.content}>
          <Text style={styles.sectionTitle}>Kategoriler</Text>
          <Text style={styles.sectionSubtitle}>
            Hangi konuda kendini test etmek istiyorsun?
          </Text>

          <TextInput
            style={styles.searchInput}
            value={categoryQuery}
            onChangeText={setCategoryQuery}
            placeholder="Kategori ara (ad veya açıklama)"
            placeholderTextColor="#718096"
            autoCorrect={false}
            accessibilityLabel="Kategorilerde ara"
          />
          <Text style={styles.searchCount} accessibilityLiveRegion="polite">
            {visibleCategories.length} / {categories.length} kategori
          </Text>
          <ScrollView
            contentContainerStyle={styles.categoriesContainer}
            showsVerticalScrollIndicator={false}
          >
            {visibleCategories.map((category) => (
              <CategoryCard
                key={category.id}
                category={category}
                index={categories.indexOf(category)}
              />
            ))}
            {visibleCategories.length === 0 && (
              <Text style={styles.emptyState}>Aramanıza uygun kategori bulunamadı.</Text>
            )}
          </ScrollView>
        </View>
      </LinearGradient>
    </RNSafeAreaView>
  );
}

